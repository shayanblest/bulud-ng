import postcss from "postcss";
/** Keep shell tokens critical; route-only component tokens load with their first page. */
export function baseCriticalTheme(source) {
  const ast = postcss.parse(source);
  const modes = [];
  ast.walkRules((rule) => {
    if (
      !rule.nodes.some(
        (node) => node.type === "decl" && node.prop === "--bulud-color-primary",
      )
    )
      return;
    const values = {};
    rule.walkDecls((decl) => {
      if (
        /^--bulud-(?:spacing|radius|shadow|font|body|color|button|switch|loading-bar)-/.test(
          decl.prop,
        )
      )
        values[decl.prop] = decl.value;
    });
    modes.push({ selector: rule.selector, values });
  });
  if (modes.length !== 3)
    throw new Error(
      "Expected default, dark and explicit light Angour boundaries",
    );
  const [base, dark, light] = modes;
  const common = Object.fromEntries(
    Object.entries(base.values).filter(
      ([key, value]) => !(key in dark.values) || dark.values[key] === value,
    ),
  );
  const lightPalette = Object.fromEntries(
    Object.entries(base.values).filter(
      ([key, value]) => key in dark.values && dark.values[key] !== value,
    ),
  );
  const darkPalette = Object.fromEntries(
    Object.entries(dark.values).filter(
      ([key, value]) => !(key in common) || common[key] !== value,
    ),
  );
  const rule = (selector, values) =>
    `${selector}{${Object.entries(values)
      .map(([key, value]) => `${key}:${value};`)
      .join("")}}`;
  const typography = postcss.root();
  for (const node of ast.nodes) {
    if (
      node.type === "rule" &&
      node.nodes.some(
        (item) =>
          item.type === "decl" && item.prop === "--bulud-font-size-control",
      )
    ) {
      const clone = node.clone();
      clone.walkDecls((decl) => {
        if (decl.prop !== "--bulud-font-size-control") decl.remove();
      });
      typography.append(clone);
    }
    if (node.type === "atrule" && node.name === "media") {
      const clone = node.clone();
      clone.walkDecls((decl) => {
        if (decl.prop !== "--bulud-font-size-control") decl.remove();
      });
      typography.append(clone);
    }
  }
  return (
    "/* Generated by npm run build:styles from the canonical Angour theme. */\n" +
    rule(base.selector, common) +
    rule(dark.selector, darkPalette) +
    rule(`${base.selector},${light.selector}`, lightPalette) +
    typography.toString() +
    "\n"
  );
}
