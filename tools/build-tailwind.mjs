import { baseCriticalTheme } from "./base-critical-theme.mjs";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwind from "@tailwindcss/postcss";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entries = JSON.parse(
  await readFile(resolve(root, "tools/tailwind-styles.json"), "utf8"),
);
const check = process.argv.includes("--check");
let count = 0;
for (const { input, output } of entries) {
  const from = resolve(root, input),
    to = resolve(root, output);
  const source = await readFile(from, "utf8");
  if (!source.includes('@import "tailwindcss/utilities" source(none)'))
    throw new Error(`Styles must explicitly disable source scanning: ${input}`);
  const result = await postcss([
    tailwind({
      base: root,
      optimize: source.includes(":host-context(") ? false : { minify: true },
    }),
  ]).process(source.replaceAll("::ng-deep", ".__bulud_ng_deep__"), {
    from,
    to,
    map: false,
  });
  if (/@apply\b|@import\s+["']tailwindcss/.test(result.css))
    throw new Error(`Uncompiled Tailwind directive in ${output}`);
  const compiled =
    "/* Generated by npm run build:styles. Edit " +
    input +
    " instead. */\n" +
    result.css.replaceAll(".__bulud_ng_deep__", "::ng-deep");
  if (check) {
    if ((await readFile(to, "utf8")) !== compiled)
      throw new Error(`Stale compiled stylesheet: ${output}`);
  } else await writeFile(to, compiled);
  count++;
}
const criticalPath = resolve(root, "projects/base/src/critical-theme.css");
const critical = baseCriticalTheme(
  await readFile(resolve(root, "projects/bulud-ng/angour.css"), "utf8"),
);
if (check) {
  if ((await readFile(criticalPath, "utf8")) !== critical)
    throw new Error("Stale base critical theme");
} else await writeFile(criticalPath, critical);
console.log(
  `${check ? "Verified" : "Built"} ${count} Tailwind stylesheets (no Preflight, no application-wide scanning).`,
);
